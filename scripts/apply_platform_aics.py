# -*- coding: utf-8 -*-
"""把 config/platform_aics.yaml 写回 ACS，并生成 .env 片段 / 远端部署命令。"""
from __future__ import annotations

import json
from datetime import datetime, timezone, timedelta
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
AIC_YAML = ROOT / "config" / "platform_aics.yaml"
ACS_DIR = ROOT / "acs"
OUT_ENV = ROOT / "config" / "platform_aics.env"
OUT_MD = ROOT / "docs" / "平台AIC登记表.md"

ACS_MAP = {
    "buyer-a": "buyer-agent-a.acs.json",
    "buyer-b": "buyer-agent-b.acs.json",
    "logistics": "logistics-agent.acs.json",
    "supplier-a": "supplier-agent-a.acs.json",
    "supplier-b": "supplier-agent-b.acs.json",
    "supplier-c": "supplier-agent-c.acs.json",
}


def main() -> None:
    data = yaml.safe_load(AIC_YAML.read_text(encoding="utf-8"))
    agents = data["agents"]
    now = datetime.now(timezone(timedelta(hours=8))).isoformat(timespec="seconds")

    env_lines = [
        "# generated by scripts/apply_platform_aics.py — 正式平台 AIC",
        f"# {now}",
    ]
    rows = []
    for key, meta in agents.items():
        aic = meta["aic"]
        env_lines.append(f"{meta['env']}={aic}")
        acs_name = ACS_MAP[key]
        path = ACS_DIR / acs_name
        acs = json.loads(path.read_text(encoding="utf-8"))
        acs["aic"] = aic
        acs["active"] = True
        acs["lastModifiedTime"] = now
        path.write_text(json.dumps(acs, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        rows.append((meta["name"], key, aic, meta["endpoint"], meta["host"]))
        print("ACS", acs_name, "->", aic)

    OUT_ENV.write_text("\n".join(env_lines) + "\n", encoding="utf-8")
    md = [
        "# 平台 AIC 登记表",
        "",
        f"> 更新时间：{now}",
        "",
        "| 名称 | id | AIC | endPoint | 部署机 |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name, key, aic, ep, host in rows:
        md.append(f"| {name} | `{key}` | `{aic}` | `{ep}` | {host} |")
    md.append("")
    md.append("环境变量片段：`config/platform_aics.env`")
    OUT_MD.write_text("\n".join(md) + "\n", encoding="utf-8")
    print("wrote", OUT_ENV)
    print("wrote", OUT_MD)


if __name__ == "__main__":
    main()
